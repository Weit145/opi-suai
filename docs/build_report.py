def para(text="", indent=True, align=WD_ALIGN_PARAGRAPH.JUSTIFY, size=14,
         bold=False, italic=False, before=0, after=0, keep_next=False,
         font=FONT):
    p = doc.add_paragraph()
    ppf = p.paragraph_format
    ppf.first_line_indent = Cm(1.25) if indent else Cm(0)
    ppf.left_indent = Cm(0)
    ppf.line_spacing = 1.5
    ppf.space_before = Pt(before)
    ppf.space_after = Pt(after)
    ppf.alignment = align
    ppf.keep_with_next = keep_next
    if text:
        run = p.add_run(text)
        set_run(run, size, bold, italic, font)
    return p


