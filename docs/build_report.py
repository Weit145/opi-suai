def save_and_convert() -> list[str]:
    doc.save(OUT_DOCX)
    cmd = [
        "soffice", "--headless",
        "-env:UserInstallation=file:///tmp/lo-profile-opi-report",
        "--convert-to", "pdf", "--outdir", str(DOCS), str(OUT_DOCX),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=240)
    txt = subprocess.run(
        ["pdftotext", "-layout", str(OUT_PDF), "-"],
        check=True, stdout=subprocess.PIPE, timeout=120,
    ).stdout.decode("utf-8", errors="replace")
    pages = txt.split("\f")
    if pages and not pages[-1].strip():
        pages.pop()
    return pages


def norm(text: str) -> str:
    text = text.replace("ё", "е").replace("Ё", "Е")
    return re.sub(r"\s+", " ", text).strip().lower()


def find_page(pages: list[str], title: str, start: int = 0) -> int:
    target = norm(title)
    for i in range(start, len(pages)):
        for line in pages[i].splitlines():
            if norm(line) == target:
                return i + 1
    short = target[:30]
    for i in range(start, len(pages)):
        if short in norm(pages[i]):
            return i + 1
    return 0


