def shade(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def add_table(headers, rows, widths, caption, font_size=TABLE_FONT,
              header_fill="E8F0EA"):
    table_caption(caption)
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    table.allow_autofit = False
    for i, width in enumerate(widths):
        table.columns[i].width = Cm(width)
    hdr = table.rows[0]
    tr_pr = hdr._tr.get_or_add_trPr()
    tbl_header = OxmlElement("w:tblHeader")
    tbl_header.set(qn("w:val"), "true")
    tr_pr.append(tbl_header)
    for i, value in enumerate(headers):
        cell = hdr.cells[i]
        cell.width = Cm(widths[i])
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        shade(cell, header_fill)
        p = cell.paragraphs[0]
        ppf = p.paragraph_format
        ppf.first_line_indent = Cm(0)
        ppf.line_spacing = 1.0
        ppf.space_before = Pt(0)
        ppf.space_after = Pt(0)
        ppf.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(str(value))
        set_run(run, font_size, True)
    for row_values in rows:
        row = table.add_row()
        tr_pr = row._tr.get_or_add_trPr()
        cant = OxmlElement("w:cantSplit")
        tr_pr.append(cant)
        for i, value in enumerate(row_values):
            cell = row.cells[i]
            cell.width = Cm(widths[i])
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            p = cell.paragraphs[0]
            ppf = p.paragraph_format
            ppf.first_line_indent = Cm(0)
            ppf.left_indent = Cm(0)
            ppf.line_spacing = 1.0
            ppf.space_before = Pt(0)
            ppf.space_after = Pt(0)
            ppf.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run = p.add_run(str(value))
            set_run(run, font_size)
    spacer = doc.add_paragraph()
    spacer.paragraph_format.first_line_indent = Cm(0)
    spacer.paragraph_format.line_spacing = 1.0
    spacer.paragraph_format.space_after = Pt(0)
    spacer.paragraph_format.space_before = Pt(0)
    return table


