def build_markdown() -> str:
    lines = ["# Доклад и ответы к защите ЛР2", "", "## Доклад руководителя (3–5 минут)", ""]
    for text in SPEECH:
        lines.append(text)
        lines.append("")
    for title, items in [
        ("Ответы на вопросы руководителя", LEADER_QA),
        ("Ответы специалиста по информационным системам", SPECIALIST_QA),
        ("Ответы DevOps-инженера", DEVOPS_QA),
    ]:
        lines.append(f"## {title}")
        lines.append("")
        for question, answer in items:
            lines.append(f"**{question}**")
            lines.append("")
            lines.append(answer)
            lines.append("")
    return "\n".join(lines)


def build_docx() -> None:
    doc = Document()
    section = doc.sections[0]
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(3)
    section.right_margin = Cm(1.5)
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)
    style.paragraph_format.line_spacing = 1.5
    style.paragraph_format.space_after = Pt(0)
    style.paragraph_format.first_line_indent = Cm(1.25)
    style.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title.paragraph_format.first_line_indent = Cm(0)
    run = title.add_run("Доклад и ответы к защите ЛР2")
    run.bold = True
    run.font.size = Pt(16)

    def heading(text):
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.space_before = Pt(10)
        p.paragraph_format.space_after = Pt(4)
        run = p.add_run(text)
        run.bold = True
        run.font.size = Pt(14)

    def body(text):
        p = doc.add_paragraph()
        run = p.add_run(text)
        run.font.size = Pt(14)

    heading("Доклад руководителя (3–5 минут)")
    for text in SPEECH:
        body(text)
    for title_text, items in [
        ("Ответы на вопросы руководителя", LEADER_QA),
        ("Ответы специалиста по информационным системам", SPECIALIST_QA),
        ("Ответы DevOps-инженера", DEVOPS_QA),
    ]:
        heading(title_text)
        for question, answer in items:
            q = doc.add_paragraph()
            q.paragraph_format.first_line_indent = Cm(0)
            q.paragraph_format.space_before = Pt(6)
            qr = q.add_run(question)
            qr.bold = True
            qr.font.size = Pt(14)
            body(answer)
    doc.save(DOCX)


MD.write_text(build_markdown(), encoding="utf-8")
build_docx()
print(f"Saved: {MD}")
print(f"Saved: {DOCX}")
